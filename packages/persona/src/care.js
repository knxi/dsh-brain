/**
 * care 信号判定（`unfinished_care` 候选的质量闸）。
 *
 * ── 为什么单独一个模块 ──
 *
 * 上一版把关键词表直接塞在 `social.js` 里，结果「是本项目的 Team Lead，需向其汇报」
 * 「备份体检踩到两个坑并已修复」「要结果不要流程汇报」这三条稳定事实/偏好，
 * 全都因为命中「汇报」「体检」被生成成「上次你提到…后来怎么样了？」——读起来非常傻，
 * 而且问第三次就让人烦。这是主人打开 dry-run 会直接看到的第一屏。
 *
 * 修法不是把权重调低（那只是让它「更不容易过门槛」，垃圾还是会被造出来），
 * 而是**在生成源头就只认真的有「后续状态」的事**，再加上一道硬闸：
 *
 * | 判定 | 含义 | 后果 |
 * |---|---|---|
 * | `strong` | 身体 / 情绪 / 有时点的具体安排 | 正常评分，并拿「来源质量分」 |
 * | `weak` | 只命中泛词（加班/汇报/项目…） | 候选照常生成但被 `source_quality` 硬闸挡掉 |
 * | `null` | 都没命中 | 不生成 |
 *
 * 另外两条独立过滤（在 `social.js` 里）：
 * - 记忆类型只认 `episode` / `commitment`（`profile` / `semantic` / `boundary` 是稳定事实）；
 * - 正文含「已修复/搞定了/…」的**根本不问**（对方早就收尾了，问等于没读）。
 *
 * 判不出来的方向永远是「少问一句」——这个不对称是故意的。
 */

/**
 * **强** care 信号：有「好了没有 / 缓过来没有 / 顺不顺」的事。
 *
 * 每个词为什么算 care（按组）：
 * - 身体：生病/感冒/发烧/咳嗽/不舒服/头疼/头痛/胃疼/肚子疼/疼得/医院/看病/吃药/
 *   失眠/睡不着/没睡好/熬夜/通宵/住院/手术/复查 —— 有恢复状态。
 * - 情绪：好烦/很烦/烦死/烦躁/心烦/压力大/焦虑/难受/郁闷/崩溃/委屈/好累/太累/累到/疲惫
 *   —— 有「缓过来没有」。
 * - 具体安排：明天要/这周要/下周要/要去/面试/考试/出差/搬家 —— 有时点、有后续结果可追问。
 *
 * 刻意**不收**（每个都踩过坑）：
 * - 「累」「烦」「疼」单字 —— 会命中「积累」「麻烦」「心疼」的一部分；
 * - 「汇报」「体检」「加班」「开会」「项目」「安排」「计划」—— 稳定事实/工作流程，
 *   没有「后来怎么样了」；「备份体检」「向其汇报」就是这么误命中的；
 * - 「重要」「赶工」—— 太泛，几乎每段工作记录都能命中。
 */
export const CARE_STRONG_KEYWORDS = Object.freeze([
  // 身体
  '生病', '感冒', '发烧', '咳嗽', '不舒服', '头疼', '头痛', '胃疼', '肚子疼', '疼得',
  '医院', '看病', '吃药', '失眠', '睡不着', '没睡好', '熬夜', '通宵', '住院', '手术', '复查',
  // 情绪
  '好烦', '很烦', '烦死', '烦躁', '心烦', '压力大', '焦虑', '难受', '郁闷', '崩溃', '委屈',
  '好累', '太累', '累到', '疲惫',
  // 具体安排（有时点、有后续）
  '明天要', '这周要', '下周要', '要去', '面试', '考试', '出差', '搬家',
]);

/**
 * 弱 care 信号：能匹配，但算不上关心。
 * 命中后候选会被 `source_quality` 硬闸挡掉（不是加权压低，而是直接不过门槛）；
 * 留在表里是为了 dry-run 的「被挡下的」列表能解释原因，而不是让它们默默消失。
 *
 * 刻意**不收**「忙」「项目」：真实库里它们命中率极高且几乎全是误报——
 * 「要求帮忙在某某页面答题」被「帮**忙**」命中、「外置大脑项**目**实测…」被「项目」命中。
 * 这类误命中连「弱信号」都算不上，只会污染第一屏，所以直接不给它们开口子。
 */
export const CARE_WEAK_KEYWORDS = Object.freeze(['加班', '开会', '汇报', '体检', '安排', '计划']);

/**
 * 「已经收尾」的语义标记：命中的记忆**根本不生成关心候选**。
 * 「备份体检踩到两个坑并已修复」就是被这一条拦下的——已经修好了，
 * 再问「后来怎么样了」等于没读。
 */
export const CARE_COMPLETED_MARKERS = Object.freeze([
  '已修复', '已修好', '已解决', '已完成', '已处理', '已恢复', '搞定了', '搞定', '解决了',
  '修好了', '弄好了', '处理完了', '收尾了', '没事了', '好了',
]);

/**
 * care 信号强度判定（纯函数，导出给测试与文档对拍）。
 *
 * @param {string} text
 * @returns {'strong' | 'weak' | null}
 */
export function careStrengthOf(text) {
  const value = String(text ?? '');
  if (CARE_STRONG_KEYWORDS.some((keyword) => value.includes(keyword))) return 'strong';
  if (CARE_WEAK_KEYWORDS.some((keyword) => value.includes(keyword))) return 'weak';
  return null;
}

/**
 * 这条记忆是否已经收尾（含「已修复/搞定了」等完成语义）。
 * @param {string} text
 * @returns {boolean}
 */
export function isResolvedCareText(text) {
  const value = String(text ?? '');
  return CARE_COMPLETED_MARKERS.some((marker) => value.includes(marker));
}
